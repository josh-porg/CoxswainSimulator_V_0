r"""The arm draw on its own clock: the elbow's time law through the drive, from sourced population data (SOURCES §209).

Through the leg drive a rower's arms are held long. The triceps and the wrist flexors are active to keep them so: their
peaks fall at 34 % and 45 % of the drive. Then the elbow flexes in one smooth movement to the finish, with the biceps,
brachioradialis and posterior deltoid peaking together at 55 % (Pitto et al. 2024, 12 national-level scullers on water).
The published mean elbow flexion (their Fig. 2, digitised in ``data/literature/pitto2024_elbow_drive.csv``) is fitted
to 1.3° rms by a held angle followed by a minimum-jerk movement (Flash & Hogan 1985) that ends at rest at the finish:

.. math::

    \theta_e(x) = \theta_h + (\theta_f - \theta_h)\, m\!\left(\frac{x - x_a}{1 - x_a}\right), \qquad
    m(s) = 10s^3 - 15s^4 + 6s^5 \quad (0 \le s \le 1)

where :math:`x` is the drive's time fraction, :math:`\theta_h` = 10.4° the held flexion and :math:`x_a` = 0.465 the
onset. Both come from the population fit (``fit_population``). The amplitude :math:`\theta_f` is *not* taken from the
paper: the hand must arrive at the rig's finish angle, so the finish flexion is solved from the body and the rig, and
the paper's 100° (±~20°, its band) is then the check. Minimum jerk starts and ends with zero velocity and
acceleration, so the hand's path stays C2 where the draw begins: there is no hand-over to blend.

The draw sets the shoulder-to-grip distance (law of cosines; flexion 0 = straight):

.. math::

    r(\theta_e) = \sqrt{u^2 + f^2 + 2uf\cos\theta_e}

with :math:`u` the upper arm and :math:`f` the forearm plus hand to the grip. The hand is then wherever the grip's arc
lies at that distance from the shoulders the body provides (``research/crew/onwater_body.body_drive_table``).

The arms' return through the recovery is the same movement reversed: from the finish flexion, starting at rest, a
minimum-jerk extension back to the held flexion by 75 % of the recovery (``RETURN_END``, fitted to the same figure,
3.1° rms; the population straightens a further ~6° late in the recovery, 2 mm of reach, which one held angle for the
whole cycle forgoes). So the hand is generated by the body around the whole cycle, C2 at the finish.

Caveats: the sample is male scullers at race rate; the wrist (within ±12° until just before the finish in the same
figure) and the shoulder girdle are not in the reach; the draw's shape is kinematic. A muscle-driven draw (the elbow
torque generator of ``joint_muscles`` against the handle force) is the refinement; this clock is its target.
"""
from __future__ import annotations

import os
from dataclasses import dataclass

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PITTO_FILE = os.path.join(ROOT, "data", "literature", "pitto2024_elbow_drive.csv")
PITTO_RECOVERY_FILE = os.path.join(ROOT, "data", "literature", "pitto2024_elbow_recovery.csv")

#: the population fit to Pitto et al. 2024 Fig. 2 (``fit_population``; pinned by tests/unit/test_arm_draw.py)
HOLD_FLEXION = float(np.radians(10.4))      # held elbow flexion before the draw, rad
DRAW_ONSET = 0.465                          # drive fraction at which the draw starts
POPULATION_FINISH_FLEXION = float(np.radians(100.5))   # the fit's finish flexion: a check, not an input
RETURN_END = 0.751                          # recovery fraction by which the arms are back at the held flexion


def minimum_jerk(s):
    """``(m, dm/ds, d2m/ds2)`` of the minimum-jerk profile, clamped to 0 before and 1 after."""
    s = np.clip(np.asarray(s, dtype=float), 0.0, 1.0)
    return (10 * s**3 - 15 * s**4 + 6 * s**5, 30 * s**2 - 60 * s**3 + 30 * s**4, 60 * s - 180 * s**2 + 120 * s**3)


def reach(upper, fore, flexion):
    """Shoulder-to-grip distance (m) at elbow ``flexion`` (rad, 0 = straight)."""
    return np.sqrt(upper**2 + fore**2 + 2.0 * upper * fore * np.cos(flexion))


@dataclass(frozen=True)
class ElbowDraw:
    """The elbow's time law through the drive: held, then a minimum-jerk draw to ``finish`` at the finish."""

    finish: float = POPULATION_FINISH_FLEXION
    hold: float = HOLD_FLEXION
    onset: float = DRAW_ONSET
    return_end: float = RETURN_END

    def flexion(self, x):
        """Elbow flexion (rad) at drive fraction ``x``."""
        m = minimum_jerk((np.asarray(x, dtype=float) - self.onset) / (1.0 - self.onset))[0]
        return self.hold + (self.finish - self.hold) * m

    def rate(self, x):
        """d(flexion)/dx, rad per unit drive fraction."""
        dm = minimum_jerk((np.asarray(x, dtype=float) - self.onset) / (1.0 - self.onset))[1]
        return (self.finish - self.hold) * dm / (1.0 - self.onset)

    def recovery_flexion(self, y):
        """Elbow flexion (rad) at recovery fraction ``y``: the arms' return, a minimum-jerk extension from the finish
        flexion (starting at rest, as the draw ended) back to the held flexion by ``return_end``, then held."""
        m = minimum_jerk(np.asarray(y, dtype=float) / self.return_end)[0]
        return self.finish - (self.finish - self.hold) * m


def population_curve():
    """``(drive_fraction, elbow_flexion_deg)`` digitised from Pitto et al. 2024 Fig. 2, drive only."""
    d = np.genfromtxt(PITTO_FILE, delimiter=",", skip_header=2)
    keep = d[:, 0] <= 1.0
    return d[keep, 0], d[keep, 1]


def population_recovery_curve():
    """``(recovery_fraction, elbow_flexion_deg)`` from the same figure, finish to catch."""
    d = np.genfromtxt(PITTO_RECOVERY_FILE, delimiter=",", skip_header=2)
    return d[:, 0], d[:, 1]


def fit_population_return(hold_deg=None, finish_deg=None):
    """The return's end (recovery fraction) by least squares, the movement starting at rest at the finish and ending
    at the held flexion (both from the drive's fit unless given). Returns ``(return_end, rms_deg)``."""
    from scipy.optimize import least_squares
    h0, _x, f0, _r = fit_population()
    h, f = np.radians(hold_deg if hold_deg is not None else h0), np.radians(finish_deg if finish_deg is not None else f0)
    y, th = population_recovery_curve()

    def resid(p):
        return np.degrees(ElbowDraw(finish=f, hold=h, return_end=p[0]).recovery_flexion(y)) - th
    r = least_squares(resid, [0.8])
    return float(r.x[0]), float(np.sqrt(np.mean(r.fun**2)))


def fit_population():
    """Least-squares fit of the held angle, onset and finish flexion to the population curve, the draw ending at the
    finish. Returns ``(hold_deg, onset, finish_deg, rms_deg)``."""
    from scipy.optimize import least_squares
    x, y = population_curve()

    def resid(p):
        d = ElbowDraw(finish=np.radians(p[2]), hold=np.radians(p[1]), onset=p[0])
        return np.degrees(d.flexion(x)) - y
    r = least_squares(resid, [0.45, 10.0, 100.0])
    return float(r.x[1]), float(r.x[0]), float(r.x[2]), float(np.sqrt(np.mean(r.fun**2)))
