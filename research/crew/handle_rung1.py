"""Phase 4.3, rung 1: hands on the handle, on two measured scullers. Nothing is fitted.

    python research/crew/handle_rung1.py [--strokes 14]

``DynamicOarSimulator(crew="handle")``: the body is the research profile's prescribed body and
its hands stay on the handle, so the oar angle is the hands' sweep for the whole stroke and the
handle force is the constraint's reaction ([CR06]'s architecture, reproduced in
research/cr06/reproduce_model1.py). The blade enters and leaves at zero normal velocity. Speed,
speed fluctuation and handle power are all *predicted*: no power is imposed.

Each athlete's own rig and arc; the stroke timing is either the model's ergometer law
(Telfer) or [K05]'s on-water single-scull rhythm (sourced, predicts both athletes' drive
fractions to 0.006). Also reported: the speed the prediction implies at the athlete's measured
power by the cube law, so speed is compared at equal power.
"""
from __future__ import annotations

import argparse
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path[:0] = [ROOT, os.path.join(ROOT, "research", "blade"), os.path.join(ROOT, "research", "biorow")]
import validate_blade as V                                       # noqa: E402

from coxswain.crew.stroke import OnWaterTiming, StrokeTiming     # noqa: E402
from coxswain.sim.control import Coxswain                        # noqa: E402
from coxswain.sim.dynamic_oar import DynamicOarSimulator         # noqa: E402


#: The catch posture of the athletes' boats. "as-built": the rig as first built, where the model's arms are 30-35 %
#: bent at the catch (SOURCES sec. 169a). "straight-arms": the footboard where this boat's own rower reaches the rig's
#: catch angle with the arms held, and the drive generated by the body (coxswain.crew.drive_law.BodyCoupledDriveSweep):
#: the grip at the arm's reach from the shoulders, the reach following the elbow's own clock (arm_draw; SOURCES 209).
#: Moving the footboard alone over-stretches the arms by ~1/3 a quarter of the way into the drive.
LE26_WOMEN_STATURE = 1.787     # m, world-class women's mean ([LE26]; onwater_body.LE26_WOMEN_STATURE)
CATCH_POSTURE = "as-built"
#: The body's segment clocks, by name (coxswain.crew.body_options.CLOCKS), e.g. ("pitto2024_trunk",): the trunk on
#: the population's on-water timing (SOURCES §211). Empty: the ergometer keyframes' own timing.
BODY_CLOCKS = ()
#: The legs' and trunk's travel from a population, by name (coxswain.crew.body_options.TRAVELS), e.g. "k05_racing"
#: (SOURCES §212). None: the ergometer keyframes' own ranges.
BODY_TRAVEL = None
#: With "straight-arms": the hand chain's optional reach terms, by name (coxswain.crew.hand_chain.TERMS), e.g.
#: ("stretch",). Empty by default: the stretch's value (SOURCES §210) comes from the test athletes.
HAND_TERMS = ()


def body_for(posture=None, clocks=None, terms=None, travel=None):
    """``(BodyOptions or None, HandChain)`` for these switches: the clocks move the body; the chain's terms set the
    kinematic rower's reach allowance so the boat's own elbow solve accepts the hand."""
    from coxswain.crew.body_options import body_options
    from coxswain.crew.hand_chain import hand_chain
    clocks = BODY_CLOCKS if clocks is None else clocks
    travel = BODY_TRAVEL if travel is None else (travel or None)
    chain = hand_chain(HAND_TERMS if terms is None else terms)
    allowance = chain.reach_allowance() if (posture or CATCH_POSTURE) == "straight-arms" else None
    if not clocks and allowance is None and not travel:
        return None, chain
    return body_options(clocks, allowance, travel or None), chain


def _straight_arm_boat(build, base, chain):
    """Rebuild ``base`` with the footboard for a held-arm catch and the drive the body generates (SOURCES 209)."""
    import onwater_body as OB
    from coxswain.crew.drive_law import BodyCoupledDriveSweep
    shift = OB.straight_arm_shift(base)
    sw = base.oar_sweep
    table, draw = OB.body_drive_table(base, shift, chain=chain)
    sweep = BodyCoupledDriveSweep(catch_angle=sw.catch_angle, finish_angle=sw.finish_angle, drive=table,
                                  recovery=OB.body_recovery_table(base, shift, draw, chain=chain), onset=draw.onset)
    boat = build(shift, sweep)
    boat.footboard_shift = shift
    boat.arm_draw_onset = draw.onset
    boat.finish_elbow = float(np.degrees(draw.finish))
    boat.hand_chain = chain
    return boat


def own_travel(name):
    """The athlete's own measured leg and trunk travel as a SegmentTravel at the model's stature for them (a
    diagnostic input, as §205's own timing: measured_reach.channels; [BR24]'s trunk point carried to the shoulder)."""
    import measured_reach as MR
    from coxswain.crew.body_options import SegmentTravel
    _t, _phi, seat, tp, _f, d_p = MR.channels(name)
    m = V.ATHLETES[name][0]()
    base = boat_for(name, m, "on-water", drive_law=True, catch_posture="as-built", clocks=(), terms=(), travel=False)
    rower = base.crew[0].rower
    trunk = float(np.ptp(tp)) * (rower.trunk_length / d_p if d_p else 1.0)
    stature = float(rower.anthropometry.stature) if name == "br24" else LE26_WOMEN_STATURE
    return SegmentTravel(float(np.ptp(seat)), trunk, stature, "%s's own channels (diagnostic)" % name)


def boat_for(name, measured, timing_kind, drive_law=False, catch_posture=None, clocks=None, terms=None,
             travel=None):
    """An athlete's boat. ``clocks`` / ``terms`` / ``travel`` override BODY_CLOCKS / HAND_TERMS / BODY_TRAVEL."""
    posture = catch_posture or CATCH_POSTURE
    if posture == "straight-arms" and not drive_law:
        raise ValueError("the straight-arm catch couples the population drive law to the body: use drive_law=True")
    travel = BODY_TRAVEL if travel is None else travel
    if travel == "own":
        travel = own_travel(name)
    body, chain = body_for(posture, clocks, terms, travel)
    if name == "br24":
        import like_for_like as L
        timing = OnWaterTiming(L.RATE) if timing_kind == "on-water" else StrokeTiming(L.RATE)
        boat = L.build("arc", timing=timing, drive_law=drive_law, body=body)
        if posture == "straight-arms":
            # like_for_like's footboard_shift is measured from its catalogue work-through; the as-built boat may
            # have moved the oarlock to reach (``work_through``), so the shift is taken relative to that
            offset = L.WORK_THROUGH - boat.work_through
            boat = _straight_arm_boat(lambda sh, sw: L.build("arc", timing=timing, drive_law=drive_law,
                                                             footboard_shift=sh + offset, oar_sweep=sw, body=body),
                                      boat, chain)
        return boat
    rate = 60.0 / V.CR06_T
    timing = OnWaterTiming(rate) if timing_kind == "on-water" else StrokeTiming(rate)
    # her stature is not published: the keyframe body solves it from her leg travel; under a population's travel
    # that would read her legs as the population's ratio (2.05 m), so [LE26]'s women's mean is stated instead
    stature = None if (body is None or body.travel is None) else LE26_WOMEN_STATURE
    boat = V.cr06_boat(measured, timing, drive_law=drive_law, body=body, stature=stature)
    if posture == "straight-arms":
        stature = float(boat.crew[0].rower.anthropometry.stature)   # her stature as solved from her leg travel
        boat = _straight_arm_boat(lambda sh, sw: V.cr06_boat(measured, timing, drive_law=drive_law, footboard_shift=sh,
                                                             stature=stature, oar_sweep=sw, body=body), boat, chain)
    return boat


def predict(boat, strokes, **options):
    boat.power_scales = np.ones(boat.n_seats)
    sim = DynamicOarSimulator(boat, peak_torque=0.0, catch="sweep", crew="handle",
                              coxswain=Coxswain(rudder_override=lambda t, s: 0.0), fast=True,
                              **options)
    run = sim.run_strokes(int(strokes), surge_speed=4.3)
    last = run.strokes[-3:]
    return dict(speed=float(np.mean([s.mean_speed for s in last])),
                ivv=float(np.mean([s.surge_swing for s in last])),
                power=float(np.mean([s.handle_power for s in last])),
                drive_fraction=float(boat.timing.drive_fraction), sim=sim, run=run)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--strokes", type=int, default=14)
    a = ap.parse_args()
    for name in ("br24", "cr06"):
        measure, _build = V.ATHLETES[name]
        m = measure()
        print("\n%s measured: %.3f m/s, IVV %.1f%%, %.0f W" % (name, m["speed"], 100 * m["ivv"], m["power"]))
        for kind, law in (("ergometer", False), ("on-water", False), ("on-water", True)):
            r = predict(boat_for(name, m, kind, law), a.strokes)
            if law:
                kind = "K05 law"
            d = force_descriptors(r)
            at_power = r["speed"] * (m["power"] / r["power"]) ** (1.0 / 3.0)
            print("  %-9s timing (drive %.3f): %.3f m/s, IVV %.1f%%, %.0f W; at his/her %.0f W: %.3f m/s (%+.1f%%); "
                  "force: entry/peak %.2f, entry-to-peak %.2f s, peak/mean %.2f"
                  % (kind, r["drive_fraction"], r["speed"], 100 * r["ivv"], r["power"], m["power"],
                     at_power, 100 * (at_power / m["speed"] - 1), d["entry_fraction"], d["entry_to_peak"],
                     d["peak_over_mean"]), flush=True)



def force_descriptors(result):
    """Handle force per oar through the last stroke, from the constraint, and the descriptors
    the population sources print: force at blade entry over peak, entry-to-peak time,
    peak / mean over the drive ([LE26]: 0.17, 0.38-0.41 s, 1.61-1.68; [H20]: -, 0.39-0.43 s,
    1.87-1.90; [K05]: peak at 34.7% of the drive)."""
    sim, run = result["sim"], result["run"]
    t, y = run.last_time, run.last_states
    start = t[0]
    lock = sim.boat.rig.seats[sim._seats[0]].oarlocks[0]
    inboard = float(lock.oar.inboard)
    force = np.zeros_like(t)
    for k in range(t.size):
        # the constraint's reaction, blade added mass included when it is on
        torque = sim.handle_torques(t[k], y[:, k], sim._air_mask[:, k])[0, 0]
        force[k] = -torque / inboard                    # pull on the handle, N per oar
    wet = ~sim._air_mask[0]
    tw = t[wet]
    fw = force[wet]
    k_peak = int(np.argmax(fw))
    return dict(entry_fraction=float(fw[0] / fw[k_peak]), entry_to_peak=float(tw[k_peak] - tw[0]),
                catch_to_peak=float(tw[k_peak] - start),
                peak_over_mean=float(fw[k_peak] / fw.mean()), peak_at=float((tw[k_peak] - tw[0]) / (tw[-1] - tw[0])),
                peak=float(fw[k_peak]))


if __name__ == "__main__":
    main()
